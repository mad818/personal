/**
 * Auto-generate docs/CLAUDE_HANDOFF.md from current repo state.
 *
 * Goals:
 * - Stable output (no per-commit SHA / file-list churn) so pre-push `handoff:sync` converges.
 * - Todo + supplement + GitHub branch links + enough context to continue work immediately.
 *
 * Usage:
 *   node scripts/generate-handoff.js --write
 *   node scripts/generate-handoff.js --check
 */

const { execSync } = require('node:child_process')
const fs = require('node:fs')
const path = require('node:path')

function sh(cmd) {
  return execSync(cmd, { stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' }).trim()
}

function safe(cmd, fallback = '') {
  try {
    return sh(cmd)
  } catch {
    return fallback
  }
}

function mdEscape(s) {
  return String(s ?? '').replace(/[\\`]/g, '\\$&')
}

/** e.g. https://github.com/owner/repo from origin URL */
function parseGithubWebBase(remoteUrl) {
  if (!remoteUrl) return null
  const m = String(remoteUrl).trim().match(/github\.com[:/]([^/]+)\/([^/]+?)(?:\.git)?$/i)
  if (!m) return null
  return `https://github.com/${m[1]}/${m[2]}`
}

function getTopTodoLines(todoPathAbs) {
  const raw = fs.readFileSync(todoPathAbs, 'utf8')
  const lines = raw.split(/\r?\n/)
  const start = lines.findIndex((l) => l.trim() === '## Next Up')
  if (start === -1) return []
  const out = []
  for (let i = start + 1; i < lines.length; i++) {
    const l = lines[i]
    if (l.startsWith('## ')) break
    if (l.trim().startsWith('- [ ] ')) out.push(l.trim().replace('- [ ] ', '- '))
    if (out.length >= 10) break
  }
  return out
}

function buildHandoff() {
  const repoRoot = process.cwd()

  const packageJson = JSON.parse(fs.readFileSync(path.join(repoRoot, 'package.json'), 'utf8'))
  const verifyCmd = packageJson?.scripts?.verify ? 'npm run verify' : 'npx tsc --noEmit'
  const devCmd = packageJson?.scripts?.dev ? 'npm run dev' : 'npm run dev'

  const todoAbs = path.join(repoRoot, 'tasks', 'todo.md')
  const nextUp = fs.existsSync(todoAbs) ? getTopTodoLines(todoAbs) : []

  const originUrl = safe('git remote get-url origin', '')
  const ghBase = parseGithubWebBase(originUrl)
  // CI checks out detached HEAD: abbrev-ref is "HEAD", not the branch name. Prefer GitHub env.
  const branch = (() => {
    if (process.env.GITHUB_HEAD_REF) return process.env.GITHUB_HEAD_REF
    const ref = process.env.GITHUB_REF || ''
    const m = ref.match(/^refs\/heads\/(.+)$/)
    if (m) return m[1]
    const ab = safe('git rev-parse --abbrev-ref HEAD', '')
    if (ab && ab !== 'HEAD') return ab
    return 'main'
  })()

  const supplementPath = path.join(repoRoot, 'docs', 'handoff-supplement.md')
  const supplement = fs.existsSync(supplementPath)
    ? '\n' + String(fs.readFileSync(supplementPath, 'utf8')).replace(/\r\n/g, '\n').trim() + '\n'
    : ''

  const handoff = [
    '## Nexus Prime — Claude Desktop Handoff (AUTO)',
    '',
    '**Regenerated by:** `scripts/generate-handoff.js` (`npm run handoff:write`, or pre-push `handoff:sync`).',
    'Per-commit message / SHA / file lists are **omitted** here so this file stays stable across handoff-only commits.',
    '',
    ...(ghBase
      ? [
          '### Git (remote)',
          '',
          `- **origin:** \`${mdEscape(originUrl)}\``,
          `- **Branch:** \`${mdEscape(branch)}\` — [browse tree](${ghBase}/tree/${encodeURIComponent(branch)}) · [commit history](${ghBase}/commits/${encodeURIComponent(branch)})`,
          '',
        ]
      : []),
    '### Project purpose',
    '',
    'Nexus Prime is a **free, open-source, self-hosted intelligence dashboard** that runs locally (no cloud backend, no DB).',
    'It aggregates markets, geopolitics, cyber, ops, IoT, and includes an AI agent (Claude via server proxy or local Ollama).',
    '',
    '### Development stage',
    '',
    '- Next.js 14 app is the active surface (`app/`, `components/`, `lib/`, `store/`).',
    '- `nexus-final.html` remains as legacy reference and should stay single-file.',
    '',
    '### OS / machine context (Windows or macOS)',
    '',
    'This repo is used on **Windows (PowerShell)** and **macOS (zsh)**. Start every new machine by confirming the basics:',
    '',
    '```bash',
    '# Where am I? (prints the repo root path)',
    'node -p "process.cwd()"',
    '',
    '# What OS is this Node running on? (win32 / darwin / linux)',
    'node -p "process.platform"',
    '',
    '# Confirm Node + npm',
    'node -v',
    'npm -v',
    '```',
    '',
    '- **Windows**: use PowerShell. Avoid Bash-only syntax like `&&` in one-liners; prefer separate commands.',
    '- **macOS**: use Terminal/zsh. Bash one-liners generally work.',
    '',
    '### Run + verify',
    '',
    '```bash',
    'npm install',
    devCmd,
    '```',
    '',
    '**Always verify after edits:**',
    '',
    '```bash',
    verifyCmd,
    '```',
    '',
    '### Security + ops constraints',
    '',
    '- Secrets live in `.env.local` (never commit). See `.env.example`.',
    '- Server routes are protected by `NEXUS_TOKEN` and CSP is enforced in `next.config.js`.',
    '- Prefer server-side API routes for external fetches to avoid CSP/CORS issues.',
    '',
    '### Latest commit (inspect locally)',
    '',
    '```bash',
    'git log -1 --oneline',
    'git show --stat HEAD',
    '```',
    '',
    '### What’s next (from `tasks/todo.md`)',
    '',
    ...(nextUp.length ? nextUp : ['- Review `tasks/todo.md` → `## Next Up`']),
    '',
    '### Where to look',
    '',
    '- **Tabs**: `app/[tab]/page.tsx`',
    '- **State**: `store/useStore.ts`',
    '- **AI**: `lib/agent.ts`, `lib/ai.ts`, `app/api/ai/*`, `app/api/tools/*`',
    '- **Diagnostics**: `app/api/status/*`, `app/api/verify/*`, `docs/metrics/*`',
    '- **Deployment / ideas:** `docs/deployment/`, `docs/ideas/assimilated-ecosystem.md`, `Dockerfile`',
    '',
    ...(supplement ? ['### Continuation notes (committed supplement)', '', supplement] : []),
  ].join('\n')

  return handoff
}

function normalizeNewlines(s) {
  return s.replace(/\r\n/g, '\n')
}

function main() {
  const args = process.argv.slice(2)
  const write = args.includes('--write')
  const check = args.includes('--check')
  if (!write && !check) {
    console.error('Usage: node scripts/generate-handoff.js --write|--check')
    process.exit(2)
  }

  const outPath = path.join(process.cwd(), 'docs', 'CLAUDE_HANDOFF.md')
  const next = normalizeNewlines(buildHandoff()).trim() + '\n'
  const cur = fs.existsSync(outPath) ? normalizeNewlines(fs.readFileSync(outPath, 'utf8')) : ''

  if (check) {
    if (normalizeNewlines(cur) !== next) {
      console.error('docs/CLAUDE_HANDOFF.md is stale. Run: npm run handoff:write')
      process.exit(1)
    }
    console.log('Handoff OK: docs/CLAUDE_HANDOFF.md is up to date.')
    return
  }

  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  fs.writeFileSync(outPath, next, 'utf8')
  console.log(`Wrote ${outPath}`)
}

main()

