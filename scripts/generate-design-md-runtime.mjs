import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const designPath = path.join(repoRoot, "DESIGN.md");
const cssPath = path.join(repoRoot, "app", "design-md.generated.css");
const tsPath = path.join(repoRoot, "lib", "generated", "designMdRuntime.ts");
const checkMode = process.argv.includes("--check");

function readDesignFrontmatter() {
  const raw = fs.readFileSync(designPath, "utf8");
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) {
    throw new Error("DESIGN.md must start with YAML frontmatter.");
  }
  return YAML.parse(match[1]);
}

function normalizeCssValue(value) {
  if (value === null || value === undefined) return "";
  return String(value);
}

function formatCssVariables(groups) {
  const lines = [];
  for (const [label, vars] of groups) {
    if (!vars || typeof vars !== "object") continue;
    lines.push(`  /* ${label} */`);
    for (const [key, value] of Object.entries(vars)) {
      const name = key.startsWith("--") ? key : `--${key}`;
      lines.push(`  ${name}: ${normalizeCssValue(value)};`);
    }
  }
  return lines.join("\n");
}

function surfaceSelector(surfaceId) {
  return [
    `html[data-nexus-surface="${surfaceId}"]`,
    `[data-surface="${surfaceId}"]`,
    `.nexus-shell-stage--${surfaceId}`,
    `.nexus-shell-hero--${surfaceId}`,
  ].join(",\n");
}

function buildCss(design) {
  const cssVariables = design.cssVariables ?? {};
  const surfaces = design.surfaces ?? {};
  const rootGroups = [
    ["Core tokens from DESIGN.md", cssVariables.root],
    ["UX5 surface tokens", cssVariables.ux5],
    ["UX6 surface tokens", cssVariables.ux6],
    ["UX7 surface tokens", cssVariables.ux7],
  ];
  const css = [
    "/* This file is generated by scripts/generate-design-md-runtime.mjs from DESIGN.md. */",
    "/* Do not edit by hand. */",
    "",
    ":root {",
    formatCssVariables(rootGroups),
    "}",
    "",
    'html[data-nexus-motion-profile="reduced"] {',
    formatCssVariables([["Reduced motion speed tokens", cssVariables.reducedMotion]]),
    "}",
    "",
    ...Object.entries(surfaces).flatMap(([surfaceId, surface]) => [
      `${surfaceSelector(surfaceId)} {`,
      `  --nexus-design-surface-accent-a: ${surface.accentA};`,
      `  --nexus-design-surface-accent-b: ${surface.accentB};`,
      `  --nexus-surface-glow-start: ${surface.glowStart};`,
      `  --nexus-surface-glow-end: ${surface.glowEnd};`,
      `  --nexus-surface-edge: ${surface.edge};`,
      "}",
      "",
    ]),
  ].join("\n");

  return `${css.trimEnd()}\n`;
}

function durationToMs(value) {
  const raw = String(value).trim();
  if (raw.endsWith("ms")) return Number.parseFloat(raw);
  if (raw.endsWith("s")) return Number.parseFloat(raw) * 1000;
  return Number.parseFloat(raw);
}

function buildTs(design) {
  const motion = design.motion ?? {};
  const durations = motion.durations ?? {};
  const ease = motion.ease ?? {};
  const density = design.density ?? {};
  const surfaces = design.surfaces ?? {};
  const payload = {
    tasteProfile: {
      designVariance: Number(density.designVariance ?? 7),
      motionIntensity: Number(density.motionIntensity ?? 6),
      visualDensity: Number(density.visualDensity ?? 7),
    },
    motion: {
      profileDefault: motion.profileDefault ?? "flagship",
      durations: {
        fastMs: durationToMs(durations.fast ?? "180ms"),
        mediumMs: durationToMs(durations.medium ?? "280ms"),
        slowMs: durationToMs(durations.slow ?? "480ms"),
        reducedFastMs: durationToMs(durations["reduced-fast"] ?? "10ms"),
        fastSec: durationToMs(durations.fast ?? "180ms") / 1000,
        mediumSec: durationToMs(durations.medium ?? "280ms") / 1000,
        slowSec: durationToMs(durations.slow ?? "480ms") / 1000,
      },
      ease: {
        standard: ease.standard ?? [0.4, 0, 0.2, 1],
        emphasis: ease.emphasis ?? [0.22, 1, 0.36, 1],
      },
    },
    surfaces: Object.fromEntries(
      Object.entries(surfaces).map(([id, surface]) => [
        id,
        {
          visibleLabel: surface.visibleLabel,
          functionalLabel: surface.functionalLabel,
          chamberTone: surface.chamberTone,
          workplaneLabel: surface.workplaneLabel,
          supportLabel: surface.supportLabel,
          continuityLabel: surface.continuityLabel,
          routeDirective: surface.routeDirective,
          accentA: surface.accentA,
          accentB: surface.accentB,
          glowStart: surface.glowStart,
          glowEnd: surface.glowEnd,
          edge: surface.edge,
          plate: surface.plate,
        },
      ]),
    ),
  };

  return `// This file is generated by scripts/generate-design-md-runtime.mjs from DESIGN.md.\n` +
    `// Do not edit by hand.\n\n` +
    `export const DESIGN_MD_TASTE_PROFILE = ${JSON.stringify(payload.tasteProfile, null, 2)} as const;\n\n` +
    `export const DESIGN_MD_MOTION = ${JSON.stringify(payload.motion, null, 2)} as const;\n\n` +
    `export const DESIGN_MD_SURFACE_ACCENTS = ${JSON.stringify(payload.surfaces, null, 2)} as const;\n`;
}

function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function writeOrCheck(filePath, nextContent) {
  if (!checkMode) {
    ensureDir(filePath);
    fs.writeFileSync(filePath, nextContent);
    return null;
  }

  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : "";
  return current === nextContent ? null : path.relative(repoRoot, filePath);
}

function main() {
  const design = readDesignFrontmatter();
  const stale = [
    writeOrCheck(cssPath, buildCss(design)),
    writeOrCheck(tsPath, buildTs(design)),
  ].filter(Boolean);

  if (stale.length) {
    console.error(`DESIGN.md generated outputs are stale: ${stale.join(", ")}`);
    console.error("Run npm run design:generate and commit the generated files.");
    process.exitCode = 1;
    return;
  }

  if (!checkMode) {
    console.log("Generated DESIGN.md runtime outputs.");
  }
}

main();
